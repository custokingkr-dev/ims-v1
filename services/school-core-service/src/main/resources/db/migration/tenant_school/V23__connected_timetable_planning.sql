    tenant_school.school_teacher_availability,
    tenant_school.school_timetable_publications TO app_rt;
  GRANT USAGE, SELECT ON SEQUENCE
    tenant_school.school_rooms_id_seq,
    tenant_school.school_teacher_availability_id_seq,
    tenant_school.school_timetable_publications_id_seq TO app_rt;
END IF; END $$;
