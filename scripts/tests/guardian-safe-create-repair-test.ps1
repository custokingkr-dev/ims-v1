        $ErrorActionPreference = "Continue"
        $output = @($Sql | & docker exec -i $containerName psql -X -v ON_ERROR_STOP=1 `
            -U postgres -d ims -A -t -F '|' 2>&1)
        $exitCode = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $prior
        $global:LASTEXITCODE = 0
    }
    if ($exitCode -eq 0 -or (($output -join "`n") -notmatch [regex]::Escape($Expected))) {
        throw "Expected guardian repair failure containing '$Expected'.`n$($output -join "`n")"
    }
}

