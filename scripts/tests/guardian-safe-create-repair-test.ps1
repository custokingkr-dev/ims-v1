function Invoke-Psql([string]$Sql) {
    $prior = $ErrorActionPreference
    try {
        $ErrorActionPreference = "Continue"
        $output = @($Sql | & docker exec -i $containerName psql -X -v ON_ERROR_STOP=1 `
            -U postgres -d ims -A -t -F '|' 2>&1)
        $exitCode = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $prior
        $global:LASTEXITCODE = 0
    }
    if ($exitCode -ne 0) {
        throw "Guardian repair PostgreSQL fixture failed: $(($output -join "`n").Trim())"
    }
    return @($output | ForEach-Object { [string]$_ })
}

function Assert-PsqlFailure([string]$Sql, [string]$Expected) {
    $prior = $ErrorActionPreference
