// Import a reviewed checkout, never fetch mutable remote data during application startup.
// Usage: node scripts/import-trophy-catalogue.mjs <source-checkout>
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
const source = process.argv[2];
if (!source) throw new Error('Provide the trophy catalogue checkout directory.');
const products = JSON.parse(readFileSync(join(source, 'data/trophy_prices.json'), 'utf8'));
const codes = new Set();
const models = new Set();
for (const product of products) {
  if (!/^[A-Za-z0-9_-]+$/.test(product.model) || models.has(product.model)
    || !['Trophy', 'Economic Trophy'].includes(product.type)
    || !Number.isSafeInteger(product.startingPrice) || product.startingPrice < 0
    || !product.sizes || !Object.keys(product.sizes).length) throw new Error(`Invalid model: ${product.model}`);
  models.add(product.model);
  for (const [size, price] of Object.entries(product.sizes)) {
    const code = `T_${product.model.toUpperCase().replaceAll('-', '_')}_${size}`;
    if (!/^[A-Z]{1,3}$/.test(size) || !Number.isSafeInteger(price) || price < 0 || codes.has(code) || code.length > 60) {
      throw new Error(`Invalid/colliding variant: ${code}`);
    }
    codes.add(code);
  }
}
const dataDir = resolve('frontend/src/features/catalog/trophies');
const imageDir = resolve('frontend/public/catalog/trophies/images');
mkdirSync(dataDir, { recursive: true }); mkdirSync(imageDir, { recursive: true });
writeFileSync(join(dataDir, 'catalogue.json'), JSON.stringify(products, null, 2) + '\n');
const imageFiles = readdirSync(join(source, 'images'));
const images = {};
for (const model of models) {
  const file = imageFiles.find((name) => name === `${model}.jpg`);
  if (file) { images[model] = file; copyFileSync(join(source, 'images', file), join(imageDir, file)); }
}
writeFileSync(join(dataDir, 'images.json'), JSON.stringify(images, null, 2) + '\n');
const compact = '[\n' + products.map((product) => '  ' + JSON.stringify(product)).join(',\n') + '\n]';
const sql = `-- Imported catalogue snapshot. See docs/product/trophy-catalogue-integration.md.
-- Generated by scripts/import-trophy-catalogue.mjs. Do not modify after this migration is deployed.
-- A variant is one indivisible model/size choice, so invalid cross-model combinations cannot be submitted.
INSERT INTO catalog.product_categories
    (code, label, emoji, description, order_type, form_enabled, paged, notes_enabled, sort_order)
VALUES ('TROPHIES', 'Trophies', U&'\\+01F3C6', 'Trophies and economic trophies by model and size', 'One-time', true, false, true, 15)
ON CONFLICT (code) DO NOTHING;

INSERT INTO catalog.product_option_groups (category_code, code, label, level, scope, render)
VALUES ('TROPHIES', 'VARIANT', 'Trophy model and size', 1, 'LINE', 'SELECT')
ON CONFLICT (category_code, code) DO NOTHING;

WITH source AS (
    SELECT product, position FROM jsonb_array_elements($trophies$${compact}$trophies$::jsonb)
    WITH ORDINALITY AS data(product, position)
)
INSERT INTO catalog.product_options (group_id, code, label, spec_text, sort_order)
SELECT g.id,
       'T_' || replace(upper(s.product ->> 'model'), '-', '_') || '_' || variant.key,
       (s.product ->> 'model') || ' / Size ' || variant.key,
       (s.product ->> 'type') || CASE WHEN variant.value::numeric > 0
           THEN '; catalogue Rs. ' || variant.value ELSE '; catalogue price on request' END,
       (s.position * 10 + ascii(variant.key) - ascii('A'))::integer
FROM source s CROSS JOIN LATERAL jsonb_each_text(s.product -> 'sizes') variant
JOIN catalog.product_option_groups g ON g.category_code = 'TROPHIES' AND g.code = 'VARIANT'
ON CONFLICT (group_id, code) DO NOTHING;
`;
writeFileSync(resolve('services/school-core-service/src/main/resources/db/migration/catalog/V25__trophy_catalogue.sql'), sql);
console.log(`Imported ${products.length} models, ${codes.size} variants, ${Object.keys(images).length} matching images.`);
